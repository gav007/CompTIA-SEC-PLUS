"""Build questions/weak.js: the 6.0 "Weak Areas" domain.

It reads every results export in ../PracticeResults and picks two kinds of question:

1. Grief questions: any question you got wrong or needed a hint for. A question
   graduates (drops out) once you answer it right AND sure twice in a row after
   the last miss. Retry sessions don't count
   towards graduating, because you'd just seen the answer.
2. Weak-objective fill: for each objective scoring under 70% since 1 Oct
   (at least 5 answers), up to 10 questions you've never seen, so the set isn't
   only the exact questions you remember.

Run it after saving a new results file:
    python tools/build_weak_areas.py
weak.js only lists question ids; the questions themselves stay in domain1-5.js.
"""
import glob
import json
import os
import re
from collections import defaultdict
from datetime import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
QUIZ = os.path.dirname(HERE)
RESULTS = os.path.join(os.path.dirname(QUIZ), "PracticeResults")
OUT = os.path.join(QUIZ, "questions", "weak.js")

RECENT_FROM = "2026-10-01"
WEAK_BELOW = 70
MIN_ANSWERS = 5
FILL_PER_OBJECTIVE = 10
GRADUATE_AFTER = 2


def bank_ids():
    ids = []
    for n in range(1, 6):
        text = open(os.path.join(QUIZ, "questions", f"domain{n}.js"), encoding="utf-8").read()
        ids += re.findall(r'"id":\s*"(SEC-D\d-\d+)"', text)
    return ids


def objective_tags():
    text = open(os.path.join(QUIZ, "questions", "objectives.js"), encoding="utf-8").read()
    body = text.split("window.QUESTION_OBJECTIVES =", 1)[1]
    body = body[:body.rindex("}") + 1]
    return {k: v["o"] for k, v in json.loads(body).items()}


def sessions():
    seen = {}
    for path in glob.glob(os.path.join(RESULTS, "secplus-*.json")):
        data = json.load(open(path, encoding="utf-8"))
        for s in data.get("sessions", [data.get("session", data)]):
            seen[s.get("sessionId", path)] = s
    return sorted(seen.values(), key=lambda s: s.get("startedAt", ""))


def is_right(q):
    right = q.get("correct")
    if right is None:
        right = (q.get("score") or 0) > 0
    return bool(right) and not q.get("hinted")


def main():
    ids = bank_ids()
    tags = objective_tags()
    history = defaultdict(list)            # id -> [(clean_right, is_miss, counts_for_graduating)]
    recent = defaultdict(lambda: [0, 0])   # objective -> [asked, right]
    for s in sessions():
        source = s.get("source") or ""
        retry = "Retry" in source                       # just saw the answer: can't graduate
        repeat = retry or source.startswith(("Weak Questions", "6.0"))  # re-asks: keep out of objective scores
        day = (s.get("startedAt") or "")[:10]
        for q in s.get("questions", []):
            qid = q.get("questionId")
            if not qid or q.get("type") == "pbq":
                continue
            right = is_right(q)
            sure = q.get("confidence") == "sure"
            history[qid].append((right and sure, not right, not retry))
            obj = tags.get(qid) or q.get("objective")
            if obj and not repeat and day >= RECENT_FROM:
                recent[obj][0] += 1
                recent[obj][1] += right

    grief = []
    for qid in ids:
        h = history.get(qid)
        if not h or not any(miss for _, miss, _ in h):
            continue
        last_miss = max(i for i, (_, miss, _) in enumerate(h) if miss)
        clean_after = [ok for ok, _, counts in h[last_miss + 1:] if counts]
        streak = 0
        for ok in clean_after:
            streak = streak + 1 if ok else 0
        if streak < GRADUATE_AFTER:
            grief.append(qid)

    weak_objs = sorted(o for o, (a, r) in recent.items() if a >= MIN_ANSWERS and 100 * r / a < WEAK_BELOW)
    fill = []
    for obj in weak_objs:
        unseen = [i for i in ids if tags.get(i) == obj and i not in history]
        fill += unseen[:FILL_PER_OBJECTIVE]

    chosen = [i for i in ids if i in set(grief) | set(fill)]
    summary = {o: f"{recent[o][1]}/{recent[o][0]}" for o in weak_objs}
    js = (
        "/* 6.0 Weak Areas -- GENERATED by tools/build_weak_areas.py, do not hand-edit.\n"
        f"   Built {datetime.now():%Y-%m-%d %H:%M} from {len(sessions())} sessions.\n"
        f"   {len(grief)} grief questions + {len(fill)} unseen from weak objectives.\n"
        f"   Weak objectives since {RECENT_FROM}: {json.dumps(summary)} */\n"
        "window.WEAK_AREA_IDS = " + json.dumps(chosen) + ";\n"
        "(function () {\n"
        "  var banks = window.QUESTION_BANKS || {};\n"
        "  var byId = {};\n"
        "  Object.keys(banks).forEach(function (k) {\n"
        "    if (k !== \"weak\") banks[k].forEach(function (q) { byId[q.id] = q; });\n"
        "  });\n"
        "  banks.weak = window.WEAK_AREA_IDS.map(function (id) { return byId[id]; }).filter(Boolean);\n"
        "  window.QUESTION_BANKS = banks;\n"
        "})();\n"
    )
    open(OUT, "w", encoding="utf-8", newline="\r\n").write(js)
    print(f"weak.js: {len(chosen)} questions ({len(grief)} grief + {len(fill)} fill)")
    print("weak objectives:", summary)
    per = defaultdict(int)
    for i in chosen:
        per[tags.get(i, "?")] += 1
    print("per objective:", dict(sorted(per.items())))


if __name__ == "__main__":
    main()
