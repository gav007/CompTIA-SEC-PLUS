#!/usr/bin/env python3
"""Tag every question in questions/domain<N>.js with a SY0-701 objective (1.1 - 5.6).

Usage (from the QUIZ folder):
    python tools/classify_objectives.py            # all five domains
    python tools/classify_objectives.py 2          # one domain, for a pilot

Writes:
    questions/objectives.js         window.QUESTION_OBJECTIVES + window.OBJECTIVE_META
    tools/objective-review.md       what landed where, and what needs a human

Why a separate file
-------------------
questions/domain<N>.js is GENERATED by extract_domain.py. Tags written into
those files would vanish on the next re-run, so they live in their own file
keyed by question id. Re-running the extractor cannot lose them, and a question
that disappears from a bank simply stops being looked up.

How the tagging works
---------------------
The objectives document lists, for every objective, the exact terms CompTIA
expects ("Honeytoken", "Annualized loss expectancy (ALE)", ...). Those term
trees are the classifier: a question is scored against the objectives OF ITS OWN
DOMAIN by how many of their terms it uses. Knowing the domain already is what
makes this accurate - the choice is between 4 and 9 objectives, never 28.

Three things keep it honest:

1. Generic terms are down-weighted. "Encryption" appears under 1.4, 2.5, 3.3
   and 5.1; "Honeytoken" appears once. Weight is inverse to how many objectives
   in the domain use the term, so distinctive terms decide the match.
2. Longer terms outrank shorter ones. Matching "business impact analysis" is
   stronger evidence than matching "impact".
3. The stem and answers count double the explanation. The explanation often
   discusses the distractors, which belong to other objectives.

A question is tagged "high" confidence only when it has a clear winner. Anything
close, or with little evidence either way, is tagged "review" and listed in the
report rather than filed silently in the wrong cluster.
"""
