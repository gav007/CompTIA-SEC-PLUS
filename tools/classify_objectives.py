def parse_objectives(path):
    """-> {objective_id: {"domain": "2.0", "directive": str, "terms": [str]}}"""
    text = path.read_text(encoding="utf-8", errors="replace")
    blocks = re.split(r"^## OBJECTIVE ", text, flags=re.M)[1:]
    out = {}
    for block in blocks:
        oid = re.match(r"([0-9]+\.[0-9]+)", block)
        if not oid:
            continue
        oid = oid.group(1)
        body = block.split("## ", 1)[0]
        dom = re.search(r'domain_id:\s*"([^"]+)"', body)
        directive = re.search(r'directive_exact:\s*"([^"]+)"', body)
        terms = re.findall(r'^\s*(?:-\s*)?term:\s*"([^"]+)"', body, re.M)
        out[oid] = {
            "domain": dom.group(1) if dom else oid.split(".")[0] + ".0",
            "directive": directive.group(1) if directive else "",
            "terms": terms,
        }
    return out


def aliases(term):
    """"Single loss expectancy (SLE)" -> ["single loss expectancy", "SLE"].

    The acronym is kept case-sensitive so "SLE" does not match inside a word,
    while the phrase is matched case-insensitively.
    """
    out = []
    m = re.match(r"^(.*?)\s*\(([^)]+)\)\s*$", term)
    if m:
        phrase, acro = m.group(1).strip(), m.group(2).strip()
        if phrase:
            out.append(("phrase", phrase))
        # Only treat it as an acronym if it actually looks like one.
        if re.fullmatch(r"[A-Za-z0-9./-]{2,12}", acro) and acro.upper() == acro:
            out.append(("acronym", acro))
        elif acro:
            out.append(("phrase", acro))
    else:
        # "Allow lists/deny lists" -> both halves, plus the whole thing.
        out.append(("phrase", term))
        if "/" in term and len(term) > 12:
            for part in term.split("/"):
                part = part.strip()
                if len(part) >= 5:
                    out.append(("phrase", part))
    return out


def build_index(objectives):
    """Per domain: {objective: [(kind, needle, weight)]}, weighted by rarity."""
    per_domain = defaultdict(lambda: defaultdict(list))
    for oid, meta in objectives.items():
        for term in meta["terms"]:
            if term.strip().lower() in STOP_TERMS:
                continue
            for kind, needle in aliases(term):
                if kind == "phrase" and len(needle) < 5:
                    continue
                per_domain[meta["domain"]][oid].append((kind, needle))
    # Alias terms join their objective's list. They are deliberately specific,
    # so they get the same treatment as any other rare term.
    for oid, extra in ALIASES.items():
        if oid not in objectives:
            continue
        domain = objectives[oid]["domain"]
        for needle in extra:
            kind = "acronym" if re.fullmatch(r"[A-Z0-9.+-]{2,12}", needle) else "phrase"
            per_domain[domain][oid].append((kind, needle))

    indexed = {}
    for domain, by_obj in per_domain.items():
        # How many objectives in this domain use each needle?
        spread = Counter()
        for oid, needles in by_obj.items():
            for _, needle in set(needles):
                spread[needle.lower()] += 1
        indexed[domain] = {}
        for oid, needles in by_obj.items():
            scored = []
            for kind, needle in sorted(set(needles)):
                n = spread[needle.lower()]
                words = len(needle.split())
                weight = (1.0 / n) * (1.0 + 0.6 * (words - 1))
                if kind == "acronym":
                    weight *= 1.4          # acronyms are precise
                scored.append((kind, needle, weight))
            indexed[domain][oid] = scored
    return indexed


def load_bank(n):
    path = QUIZ_DIR / "questions" / f"domain{n}.js"
    src = path.read_text(encoding="utf-8", errors="replace")
    # Anchor on the assignment itself: the first "[" after window.QUESTION_BANKS
    # is the ["domainN"] subscript, not the array.
    assign = re.search(r'window\.QUESTION_BANKS\[\s*"domain%d"\s*\]\s*=\s*' % n, src)
    if not assign:
        raise SystemExit(f"{path.name}: could not find the bank assignment")
    start = src.index("[", assign.end() - 1)
    depth, end = 0, None
    for i, ch in enumerate(src[start:], start):
        if ch == "[":
            depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    return json.loads(src[start:end])


def count_hits(kind, needle, strong, weak):
    if kind == "acronym":
        pat = re.compile(r"(?<![A-Za-z0-9])" + re.escape(needle) + r"(?![A-Za-z0-9])")
        return len(pat.findall(strong)) * 2 + len(pat.findall(weak))
    pat = re.compile(r"(?<![a-z])" + re.escape(needle.lower()) + r"(?![a-z])")
    return len(pat.findall(strong.lower())) * 2 + len(pat.findall(weak.lower()))


def classify(q, candidates):
    strong = q["question"] + " \n " + " \n ".join(q.get("answers", []))
    weak = q.get("explanation", "") + " " + q.get("exhibit", "")
    scores, evidence = {}, {}
    for oid, needles in candidates.items():
        total, matched = 0.0, []
        for kind, needle, weight in needles:
            hits = count_hits(kind, needle, strong, weak)
            if hits:
                # A long, specific term matching is much better evidence than a
                # short common one matching repeatedly, so length drives the
                # score and repeats only nudge it. This is what settles clashes
                # like "CIA" (1.2) against "maintenance window" (1.3).
                specificity = 1.0 + 0.35 * max(0, len(needle.split()) - 1)
                total += weight * specificity * (1 + 0.2 * (hits - 1))
                matched.append(needle)
        scores[oid] = total
        evidence[oid] = matched
    ranked = sorted(scores.items(), key=lambda kv: -kv[1])
    best, best_score = ranked[0]
    runner_up, second = (ranked[1] if len(ranked) > 1 else ("", 0.0))
    margin = best_score - second
    # One bare word is not evidence. A confident tag needs a multi-word phrase,
    # an acronym, or at least two distinct terms from the same objective --
    # otherwise a single stray "Cloud" or "Wireless" decides the cluster.
    hits = evidence[best]
    specific = any(len(h.split()) > 1 or h.isupper() for h in hits) or len(hits) >= 2
    if best_score >= 1.2 and specific and \
            (margin >= 0.6 or best_score >= 2.5 * max(second, 0.01)):
        conf = "high"
    elif best_score >= 0.6:
        conf = "low"
    else:
        conf = "none"
    return {
        "objective": best if conf != "none" else "",
        "confidence": conf,
        "score": round(best_score, 2),
        "runnerUp": runner_up,
        "runnerUpScore": round(second, 2),
        "matched": evidence[best][:6],
        "runnerUpMatched": evidence.get(runner_up, [])[:4],
    }


def main():
    wanted = [int(a) for a in sys.argv[1:]] or [1, 2, 3, 4, 5]
    objectives = parse_objectives(OBJECTIVES_MD)
    index = build_index(objectives)

    results, per_domain_counts, needs_review = {}, defaultdict(Counter), []
    for n in wanted:
        bank = load_bank(n)
        domain = f"{n}.0"
        candidates = index[domain]
        for q in bank:
            verdict = classify(q, candidates)
            if q["id"] in MANUAL_TAGS:
                verdict = {**verdict, "objective": MANUAL_TAGS[q["id"]],
                           "confidence": "manual", "matched": ["(manual override)"]}
            results[q["id"]] = verdict
            key = verdict["objective"] or "unsorted"
            per_domain_counts[domain][key] += 1
            if verdict["confidence"] not in ("high", "manual"):
                needs_review.append((q["id"], q["question"], verdict))

    # ---- questions/objectives.js -------------------------------------------
    meta = {oid: {"name": objectives[oid]["directive"], "domain": objectives[oid]["domain"]}
            for oid in sorted(objectives)}
    tags = {qid: {"o": v["objective"], "c": v["confidence"]}
            for qid, v in sorted(results.items()) if v["objective"]}
    out = QUIZ_DIR / "questions" / "objectives.js"
    out.write_text(
        "/* CompTIA Security+ SY0-701 -- objective tags per question.\n"
        "   GENERATED by tools/classify_objectives.py -- do not hand-edit;\n"
        "   add corrections to MANUAL_TAGS in that script instead.\n"
        f"   {len(tags)} of {len(results)} questions tagged.\n"
        "   o = objective id, c = confidence (high|low). Untagged questions\n"
        "   appear in the app under 'Unsorted' and are listed in\n"
        "   tools/objective-review.md. */\n"
        "window.OBJECTIVE_META = " + json.dumps(meta, indent=2) + ";\n"
        "window.QUESTION_OBJECTIVES = " + json.dumps(tags, indent=2) + ";\n",
        encoding="utf-8")

    # ---- tools/objective-review.md -----------------------------------------
    lines = ["# Objective tagging review", "",
             f"Generated by `tools/classify_objectives.py` for domain(s) {wanted}.", ""]
    total = len(results)
    high = sum(1 for v in results.values() if v["confidence"] in ("high", "manual"))
    low = sum(1 for v in results.values() if v["confidence"] == "low")
    none = total - high - low
    lines += [f"**{total} questions: {high} high confidence, {low} low, {none} unsorted.**", ""]
    for domain in sorted(per_domain_counts):
        lines += [f"## Domain {domain}", "", "| Objective | Questions | Directive |",
                  "| --- | --- | --- |"]
        counts = per_domain_counts[domain]
        for oid in sorted(k for k in counts if k != "unsorted"):
            lines.append(f"| {oid} | {counts[oid]} | {objectives[oid]['directive']} |")
        if counts["unsorted"]:
            lines.append(f"| unsorted | {counts['unsorted']} | needs a human |")
        lines.append("")
    lines += ["## Needs checking", "",
              "Low-confidence or unsorted questions, with the top two candidates.", ""]
    for qid, stem, v in needs_review:
        lines += [f"- **{qid}** [{v['confidence']}] {stem[:150]}",
                  f"  - best: {v['objective'] or '(none)'} ({v['score']}) via {v['matched']}",
                  f"  - next: {v['runnerUp']} ({v['runnerUpScore']}) via {v['runnerUpMatched']}"]
    (QUIZ_DIR / "tools" / "objective-review.md").write_text("\n".join(lines) + "\n",
                                                            encoding="utf-8")

    print(f"{total} questions classified: {high} high, {low} low, {none} unsorted")
    for domain in sorted(per_domain_counts):
        counts = per_domain_counts[domain]
        spread = ", ".join(f"{k}:{counts[k]}" for k in sorted(counts))
        print(f"  domain {domain}: {spread}")
    print(f"wrote {out.relative_to(QUIZ_DIR)} and tools/objective-review.md")


